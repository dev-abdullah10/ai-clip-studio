export function applyPresetValues(
  presetId: string,
  presets: Record<string, SubtitlePreset> = SUBTITLE_PRESETS,
): (Partial<SubtitleSettings> & { preset: string }) | null {
  const preset = presets[presetId];
  if (!preset) return null;
  const { label: _label, ...values } = preset;
  return { ...values, preset: presetId };
}
